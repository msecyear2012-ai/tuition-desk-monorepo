"use client";

import { useState, useEffect, useCallback } from "react";
import { apiClient } from "@/lib/apiClient";
import { getAuthenticatedCenter } from "@/lib/centerProfile";
import {
  Link2,
  Copy,
  Check,
  RefreshCw,
  ShieldAlert,
  ShieldCheck,
  Lock,
  ExternalLink,
  MessageCircle,
  Users,
  AlertTriangle,
  Loader2,
  Plus,
  Trash2,
  X,
} from "lucide-react";

interface LinkedStudent {
  _id: string;
  name: string;
  batch?: string;
  rollNumber?: string;
  parentWhatsApp?: string;
}

interface ParentAccessInfo {
  id: string;
  centerId: string;
  parentPhone: string;
  parentName?: string;
  tokenPrefix: string;
  status: "active" | "revoked";
  isPasswordProtected: boolean;
  linkedStudents: LinkedStudent[];
  lastAccessedAt?: string;
  createdAt?: string;
  revokedAt?: string;
  revocationReason?: string;
  /**
   * Canonical, activation-capable portal link (`/portal#token=...`) rebuilt
   * server-side from the encrypted token copy. Same link the parent already
   * holds — never regenerated by simply viewing this card.
   */
  portalUrl?: string | null;
}

interface ParentAccessResponse {
  success: boolean;
  exists: boolean;
  parentAccess: ParentAccessInfo | null;
  portalUrl?: string | null;
  error?: string;
}

interface GenerateResponse {
  success: boolean;
  portalUrl: string;
  rawToken: string;
  tokenPrefix: string;
  parentAccess: ParentAccessInfo;
  error?: string;
}

interface CandidateStudent {
  _id: string;
  name: string;
  batch?: string;
  parentWhatsApp: string;
}

export default function ParentAccessCard({
  studentId,
  studentName,
  parentPhone,
  centerName = "Tuition Center",
  onLinkGenerated,
}: {
  studentId: string;
  studentName: string;
  parentPhone: string;
  centerId?: string;
  centerName?: string;
  onLinkGenerated?: () => void;
}) {
  const [loading, setLoading] = useState(true);
  const [isOwner, setIsOwner] = useState<boolean | null>(null);
  const [access, setAccess] = useState<ParentAccessInfo | null>(null);
  const [activePortalUrl, setActivePortalUrl] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const [actionLoading, setActionLoading] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [successToast, setSuccessToast] = useState<string | null>(null);

  // Link Sibling Modal State
  const [showLinkModal, setShowLinkModal] = useState(false);
  const [candidates, setCandidates] = useState<CandidateStudent[]>([]);
  const [loadingCandidates, setLoadingCandidates] = useState(false);
  const [selectedCandidateId, setSelectedCandidateId] = useState("");

  const showToast = (msg: string) => {
    setSuccessToast(msg);
    setTimeout(() => setSuccessToast(null), 4000);
  };

  // 1. Fetch current ParentAccess state for this student
  const fetchAccessInfo = useCallback(async () => {
    if (!studentId) return;
    setLoading(true);
    setErrorMessage(null);
    try {
      const center = await getAuthenticatedCenter();
      if (center && center.role !== "owner") {
        setIsOwner(false);
        setLoading(false);
        return;
      }
      setIsOwner(true);

      const res = await apiClient<ParentAccessResponse>("/parent/access", {
        params: { studentId },
        skipCache: true,
      });

      const data = res?.data || (res as unknown as ParentAccessResponse);
      if (res && res.success) {
        if (data?.exists && data.parentAccess) {
          setAccess(data.parentAccess);
          // Server rebuilds the SAME activation link the parent already holds,
          // so owners can copy/open it without rotating (invalidating) it.
          setActivePortalUrl(
            data.portalUrl || data.parentAccess.portalUrl || null
          );
        } else {
          setAccess(null);
          setActivePortalUrl(null);
        }
      } else {
        setAccess(null);
        setActivePortalUrl(null);
      }
    } catch (err: unknown) {
      if (
        err instanceof Error &&
        (err.message.includes("Owner authorization required") ||
          err.message.includes("Access denied") ||
          err.message.includes("403"))
      ) {
        setIsOwner(false);
        setLoading(false);
        return;
      }
      const msg = err instanceof Error ? err.message : "Failed to load portal link info";
      setErrorMessage(msg);
    } finally {
      setLoading(false);
    }
  }, [studentId]);

  useEffect(() => {
    fetchAccessInfo();
  }, [fetchAccessInfo]);

  // 2. Generate new or initial portal link
  const handleGenerateLink = async () => {
    setActionLoading(true);
    setErrorMessage(null);
    try {
      const res = await apiClient<GenerateResponse>("/parent/access", {
        method: "POST",
        body: {
          action: "generate",
          studentId,
          parentPhone,
          parentName: studentName,
        },
      });

      const data = res?.data;
      const portalUrl = data?.portalUrl;
      const parentAccess = data?.parentAccess;

      if (res && res.success && portalUrl) {
        setErrorMessage(null);
        setActivePortalUrl(portalUrl);
        if (parentAccess) {
          setAccess(parentAccess);
        }
        showToast("Secure portal link generated!");
        // Re-fetch authoritative status and notify parent component
        await fetchAccessInfo();
        if (typeof onLinkGenerated === "function") {
          onLinkGenerated();
        }
      } else {
        throw new Error(res.error || "Failed to generate portal link");
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : "Failed to generate portal link";
      setErrorMessage(msg);
    } finally {
      setActionLoading(false);
    }
  };

  // 3. Regenerate portal link (invalidates old link)
  const handleRegenerateLink = async () => {
    if (!access) return;
    if (
      !window.confirm(
        "Are you sure you want to regenerate this link? The previous access link will be permanently invalidated."
      )
    ) {
      return;
    }

    setActionLoading(true);
    setErrorMessage(null);
    try {
      const res = await apiClient<GenerateResponse>("/parent/access", {
        method: "POST",
        body: {
          action: "regenerate",
          parentAccessId: access.id,
        },
      });

      const data = res?.data;
      const portalUrl = data?.portalUrl;
      const parentAccess = data?.parentAccess;

      if (res && res.success && portalUrl) {
        setErrorMessage(null);
        setActivePortalUrl(portalUrl);
        if (parentAccess) {
          setAccess(parentAccess);
        }
        showToast("New portal link generated. Previous link is now invalid.");
        await fetchAccessInfo();
        if (typeof onLinkGenerated === "function") {
          onLinkGenerated();
        }
      } else {
        throw new Error(res.error || "Failed to regenerate portal link");
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : "Failed to regenerate portal link";
      setErrorMessage(msg);
    } finally {
      setActionLoading(false);
    }
  };

  // 4. Revoke portal link
  const handleRevokeLink = async () => {
    if (!access) return;
    if (
      !window.confirm(
        "Revoking this link will immediately block parent access. Are you sure?"
      )
    ) {
      return;
    }

    setActionLoading(true);
    setErrorMessage(null);
    try {
      const res = await apiClient<{ success: boolean; parentAccess: ParentAccessInfo }>("/parent/access", {
        method: "POST",
        body: {
          action: "revoke",
          parentAccessId: access.id,
          reason: "Revoked by institute owner",
        },
      });

      if (res && res.success) {
        setActivePortalUrl(null);
        showToast("Portal link revoked. Access has been blocked.");
        await fetchAccessInfo();
      } else {
        throw new Error("Failed to revoke portal link");
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : "Failed to revoke portal link";
      setErrorMessage(msg);
    } finally {
      setActionLoading(false);
    }
  };

  // 5. Copy link to clipboard
  const handleCopyLink = () => {
    if (activePortalUrl) {
      navigator.clipboard.writeText(activePortalUrl);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
      return;
    }

    if (!access) return;

    // Legacy records created before encrypted token storage existed cannot be
    // rebuilt. Regenerating is the only option and it invalidates the old link,
    // so this must always be an explicit, warned decision.
    const shouldRegen = window.confirm(
      "This portal record has no rebuildable link. Generate a fresh link now? The previously shared link will stop working."
    );
    if (shouldRegen) {
      handleRegenerateLink();
    }
  };

  // 6. Share on WhatsApp
  const handleShareWhatsApp = () => {
    if (!activePortalUrl && access) {
      const shouldRegen = window.confirm(
        "To send an active link on WhatsApp, a fresh secure token will be generated. Proceed?"
      );
      if (shouldRegen) {
        handleRegenerateLink();
      }
      return;
    }

    if (!activePortalUrl) return;

    const message = [
      `*${centerName} — Parent VIP Portal Link*`,
      ``,
      `Dear Parent, you can track daily attendance, test performance, and fee ledgers for ${studentName} via your personal portal:`,
      `🔗 ${activePortalUrl}`,
      ``,
      `No app installation required.`,
    ].join("\n");

    const cleanDigits = String(parentPhone || "").replace(/\D/g, "");
    window.open(
      `https://wa.me/91${cleanDigits}?text=${encodeURIComponent(message)}`,
      "_blank"
    );
  };

  // 7. Load Candidates for Sibling Linking
  const openLinkSiblingModal = async () => {
    setShowLinkModal(true);
    setLoadingCandidates(true);
    try {
      const res = await apiClient<CandidateStudent[]>("/students", {
        skipCache: true,
      });
      const list = Array.isArray(res.data) ? res.data : [];
      // Filter out students already linked to this parent access
      const linkedIds = new Set(access?.linkedStudents.map((s) => String(s._id)) || [studentId]);
      const available = list.filter((s) => !linkedIds.has(String(s._id)));
      setCandidates(available);
      if (available.length > 0) {
        setSelectedCandidateId(available[0]._id);
      }
    } catch {
      setCandidates([]);
    } finally {
      setLoadingCandidates(false);
    }
  };

  // 8. Confirm Link Sibling
  const handleConfirmLinkSibling = async () => {
    if (!access || !selectedCandidateId) return;
    setActionLoading(true);
    try {
      const res = await apiClient<{ success: boolean; parentAccess: ParentAccessInfo }>("/parent/access", {
        method: "POST",
        body: {
          action: "link_student",
          parentAccessId: access.id,
          studentIdToLink: selectedCandidateId,
        },
      });

      if (res && res.success) {
        showToast("Sibling student linked to portal access!");
        setShowLinkModal(false);
        await fetchAccessInfo();
      } else {
        throw new Error(res?.error || "Failed to link student");
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : "Failed to link student";
      setErrorMessage(msg);
    } finally {
      setActionLoading(false);
    }
  };

  // 9. Unlink Student
  const handleUnlinkStudent = async (studentIdToUnlink: string) => {
    if (!access) return;
    if (!window.confirm("Are you sure you want to unlink this student from the parent portal link?")) return;

    setActionLoading(true);
    try {
      const res = await apiClient<{ success: boolean; parentAccess: ParentAccessInfo }>("/parent/access", {
        method: "POST",
        body: {
          action: "unlink_student",
          parentAccessId: access.id,
          studentIdToUnlink,
        },
      });

      if (res && res.success) {
        showToast("Student unlinked from portal access");
        await fetchAccessInfo();
      } else {
        throw new Error(res?.error || "Failed to unlink student");
      }
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : "Failed to unlink student";
      setErrorMessage(msg);
    } finally {
      setActionLoading(false);
    }
  };

  if (isOwner === false) {
    return null;
  }

  return (
    <div className="w-full max-w-full min-w-0 overflow-hidden rounded-3xl border border-slate-200/90 bg-white p-4 sm:p-5 shadow-sm space-y-4">
      {/* Toast */}
      {successToast && (
        <div className="p-3 bg-emerald-50 border border-emerald-200 text-emerald-800 rounded-2xl text-xs font-semibold flex items-center gap-2">
          <Check className="w-4 h-4 text-emerald-600" />
          <span>{successToast}</span>
        </div>
      )}

      {/* Error */}
      {errorMessage && (
        <div className="p-3 bg-rose-50 border border-rose-200 text-rose-800 rounded-2xl text-xs font-semibold flex items-center justify-between gap-2">
          <div className="flex items-center gap-2 flex-1 min-w-0">
            <AlertTriangle className="w-4 h-4 text-rose-600 flex-shrink-0" />
            <span className="flex-1 break-words">{errorMessage}</span>
          </div>
          <div className="flex items-center gap-1.5 shrink-0">
            <button
              onClick={() => {
                setErrorMessage(null);
                void handleGenerateLink();
              }}
              className="px-2 py-1 text-[11px] font-bold rounded-lg bg-rose-100 hover:bg-rose-200 text-rose-700 transition-colors"
            >
              Retry
            </button>
            <button
              onClick={() => setErrorMessage(null)}
              className="p-1 hover:bg-rose-100 rounded-lg transition-colors text-rose-600"
              title="Dismiss error"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}

      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-100">
        <div className="flex items-center gap-2.5">
          <div className="w-9 h-9 rounded-2xl bg-blue-50 text-blue-600 border border-blue-100 flex items-center justify-center">
            <Link2 className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-sm font-bold text-slate-900">
              Parent VIP Portal Access
            </h3>
            <p className="text-[11px] text-slate-500">
              Unique, high-entropy token link with optional multi-child bundling
            </p>
          </div>
        </div>

        {/* Status Badge */}
        {loading ? (
          <div className="h-6 w-20 bg-slate-100 animate-pulse rounded-full" />
        ) : !access ? (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-slate-100 text-slate-600">
            Not Generated
          </span>
        ) : access.status === "revoked" ? (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-rose-50 text-rose-700 border border-rose-200">
            <ShieldAlert className="w-3 h-3" />
            Revoked
          </span>
        ) : access.isPasswordProtected ? (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-purple-50 text-purple-700 border border-purple-200">
            <Lock className="w-3 h-3" />
            PIN Protected
          </span>
        ) : (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-emerald-50 text-emerald-700 border border-emerald-200">
            <ShieldCheck className="w-3 h-3" />
            Active Direct Link
          </span>
        )}
      </div>

      {/* Main Body */}
      {loading ? (
        <div className="py-6 flex items-center justify-center gap-2 text-slate-400 text-xs font-semibold">
          <Loader2 className="w-4 h-4 animate-spin text-blue-600" />
          <span>Checking portal access status...</span>
        </div>
      ) : !access ? (
        <div className="py-3 space-y-3">
          <p className="text-xs text-slate-600 leading-relaxed">
            No secure portal link has been generated for {studentName}&apos;s parent yet.
            Click below to generate a unique, cryptographically secure direct link.
          </p>
          <button
            onClick={handleGenerateLink}
            disabled={actionLoading}
            className="tap-bounce w-full sm:w-auto px-4 py-2.5 rounded-2xl bg-blue-600 hover:bg-blue-700 text-white font-bold text-xs flex items-center justify-center gap-2 shadow-sm transition-all"
          >
            {actionLoading ? (
              <Loader2 className="w-4 h-4 animate-spin" />
            ) : (
              <Link2 className="w-4 h-4" />
            )}
            <span>Generate Secure Portal Link</span>
          </button>
        </div>
      ) : (
        <div className="space-y-3.5 w-full max-w-full min-w-0 overflow-hidden">
          {/* Active URL Card / Token Info */}
          <div className="p-3 rounded-2xl bg-slate-50 border border-slate-200/80 space-y-2 w-full max-w-full min-w-0 overflow-hidden">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-1 text-[11px] w-full max-w-full min-w-0 overflow-hidden">
              <span className="font-semibold text-slate-500 truncate min-w-0">
                Token Hint: <code className="font-mono font-bold text-slate-800">{access.tokenPrefix}••••</code>
              </span>
              <span className="text-slate-400 shrink-0">
                Registered Phone: +91 {access.parentPhone}
              </span>
            </div>

            {activePortalUrl ? (
              <div className="flex items-center gap-2 w-full max-w-full min-w-0 overflow-hidden">
                <input
                  type="text"
                  readOnly
                  value={activePortalUrl}
                  className="flex-1 w-full min-w-0 overflow-hidden text-ellipsis bg-white border border-slate-200 rounded-xl px-3 py-1.5 text-xs font-mono text-slate-800 select-all"
                />
                <button
                  onClick={handleCopyLink}
                  className="shrink-0 px-3 py-1.5 rounded-xl bg-slate-900 text-white text-xs font-bold flex items-center gap-1.5 hover:bg-slate-800 transition-colors"
                >
                  {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                  <span>{copied ? "Copied" : "Copy"}</span>
                </button>
              </div>
            ) : (
              <div className="text-[11px] text-slate-500 italic">
                The active link could not be rebuilt for this record. Click
                &quot;Regenerate Link&quot; to issue a fresh URL (the previous
                link will stop working).
              </div>
            )}
          </div>

          {/* Action Buttons Container */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 pt-1">
            <button
              onClick={handleCopyLink}
              disabled={actionLoading || access.status === "revoked"}
              className="tap-bounce w-full px-3 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-800 font-bold text-xs flex items-center justify-center gap-1.5 transition-colors disabled:opacity-50"
            >
              {copied ? (
                <Check className="w-3.5 h-3.5 text-emerald-600 shrink-0" />
              ) : (
                <Copy className="w-3.5 h-3.5 text-slate-600 shrink-0" />
              )}
              <span className="truncate">{copied ? "Link Copied" : "Copy Link"}</span>
            </button>

            <button
              onClick={handleShareWhatsApp}
              disabled={actionLoading || access.status === "revoked"}
              className="tap-bounce w-full px-3 py-2 rounded-xl bg-emerald-50 hover:bg-emerald-100 text-emerald-800 font-bold text-xs flex items-center justify-center gap-1.5 transition-colors border border-emerald-200 disabled:opacity-50"
            >
              <MessageCircle className="w-3.5 h-3.5 text-emerald-600 shrink-0" />
              <span className="truncate">Share via WhatsApp</span>
            </button>

            {activePortalUrl && (
              <a
                href={activePortalUrl}
                target="_blank"
                rel="noreferrer"
                className="tap-bounce w-full sm:col-span-2 px-3 py-2 rounded-xl bg-blue-50 hover:bg-blue-100 text-blue-800 font-bold text-xs flex items-center justify-center gap-1.5 transition-colors border border-blue-200"
              >
                <ExternalLink className="w-3.5 h-3.5 text-blue-600 shrink-0" />
                <span className="truncate">Open Portal</span>
              </a>
            )}

            <button
              onClick={handleRegenerateLink}
              disabled={actionLoading}
              className="tap-bounce w-full px-3 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold text-xs flex items-center justify-center gap-1.5 transition-colors disabled:opacity-50"
              title="Issue fresh token and invalidate old link"
            >
              <RefreshCw
                className={`w-3.5 h-3.5 shrink-0 ${
                  actionLoading ? "animate-spin" : ""
                }`}
              />
              <span className="truncate">Regenerate Link</span>
            </button>

            {access.status === "active" ? (
              <button
                onClick={handleRevokeLink}
                disabled={actionLoading}
                className="tap-bounce w-full px-3 py-2 rounded-xl bg-rose-50 hover:bg-rose-100 text-rose-700 font-bold text-xs flex items-center justify-center gap-1.5 transition-colors border border-rose-200 disabled:opacity-50"
              >
                <ShieldAlert className="w-3.5 h-3.5 text-rose-600 shrink-0" />
                <span className="truncate">Revoke Access</span>
              </button>
            ) : (
              <button
                onClick={handleRegenerateLink}
                disabled={actionLoading}
                className="tap-bounce w-full px-3 py-2 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white font-bold text-xs flex items-center justify-center gap-1.5 transition-colors"
              >
                <ShieldCheck className="w-3.5 h-3.5 shrink-0" />
                <span className="truncate">Restore Access</span>
              </button>
            )}
          </div>

          {/* Linked Children Section */}
          <div className="pt-3 border-t border-slate-100 space-y-2 w-full max-w-full min-w-0 overflow-hidden">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold text-slate-800 flex items-center gap-1.5">
                <Users className="w-3.5 h-3.5 text-slate-500" />
                <span>Linked Children ({access.linkedStudents?.length || 1})</span>
              </span>
              <button
                onClick={openLinkSiblingModal}
                disabled={access.status === "revoked"}
                className="text-[11px] font-bold text-blue-600 hover:text-blue-800 flex items-center gap-1 disabled:opacity-50"
              >
                <Plus className="w-3 h-3" />
                <span>Link Sibling Student</span>
              </button>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 w-full max-w-full">
              {access.linkedStudents?.map((child) => (
                <div
                  key={child._id}
                  className="flex items-center justify-between p-2.5 rounded-xl bg-slate-50 border border-slate-200/70 text-xs min-w-0 overflow-hidden"
                >
                  <div className="space-y-0.5 min-w-0 overflow-hidden">
                    <span className="font-bold text-slate-800 block truncate">
                      {child.name}
                    </span>
                    <span className="text-[10px] text-slate-500 block truncate">
                      {child.batch || "Regular Batch"}
                    </span>
                  </div>

                  {access.linkedStudents.length > 1 && String(child._id) !== studentId && (
                    <button
                      onClick={() => handleUnlinkStudent(child._id)}
                      className="p-1 text-slate-400 hover:text-rose-600 transition-colors"
                      title="Unlink this student"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  )}
                </div>
              ))}
            </div>
          </div>
        </div>
      )}

      {/* Link Sibling Modal */}
      {showLinkModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-xs animate-in fade-in">
          <div className="max-w-md w-full bg-white rounded-3xl p-5 shadow-2xl space-y-4 border border-slate-100">
            <div className="flex items-center justify-between pb-2 border-b border-slate-100">
              <h4 className="text-sm font-bold text-slate-900 flex items-center gap-2">
                <Users className="w-4 h-4 text-blue-600" />
                <span>Link Sibling to this Parent Portal</span>
              </h4>
              <button onClick={() => setShowLinkModal(false)} className="text-slate-400 hover:text-slate-600">
                <X className="w-4 h-4" />
              </button>
            </div>

            <p className="text-xs text-slate-500 leading-relaxed">
              Select an enrolled student to bundle under this parent&apos;s single portal link.
              The parent will be able to switch between linked children seamlessly.
            </p>

            {loadingCandidates ? (
              <div className="py-8 flex items-center justify-center text-xs text-slate-500 gap-2">
                <Loader2 className="w-4 h-4 animate-spin text-blue-600" />
                <span>Loading available students...</span>
              </div>
            ) : candidates.length === 0 ? (
              <div className="p-4 bg-slate-50 rounded-2xl text-center text-xs text-slate-500">
                No other unlinked students found in this institute.
              </div>
            ) : (
              <div className="space-y-3">
                <label className="text-xs font-bold text-slate-700 block">
                  Select Student to Link:
                </label>
                <select
                  value={selectedCandidateId}
                  onChange={(e) => setSelectedCandidateId(e.target.value)}
                  className="w-full px-3 py-2.5 rounded-xl border border-slate-200 text-xs font-semibold text-slate-800 bg-white"
                >
                  {candidates.map((cand) => (
                    <option key={cand._id} value={cand._id}>
                      {cand.name} ({cand.batch || "No Batch"}) — +91 {cand.parentWhatsApp}
                    </option>
                  ))}
                </select>

                <div className="flex items-center justify-end gap-2 pt-2">
                  <button
                    onClick={() => setShowLinkModal(false)}
                    className="px-3.5 py-2 rounded-xl text-xs font-bold text-slate-600 hover:bg-slate-100"
                  >
                    Cancel
                  </button>
                  <button
                    onClick={handleConfirmLinkSibling}
                    disabled={actionLoading || !selectedCandidateId}
                    className="px-4 py-2 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold flex items-center gap-1.5 shadow-sm"
                  >
                    {actionLoading && <Loader2 className="w-3.5 h-3.5 animate-spin" />}
                    <span>Confirm Link</span>
                  </button>
                </div>
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
